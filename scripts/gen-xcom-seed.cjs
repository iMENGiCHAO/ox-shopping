/* Generate prisma/xcom-catalog.ts from live Shopify products.json dumps */
const fs = require("fs");
const products = JSON.parse(fs.readFileSync("/tmp/xcom-products.json", "utf8")).products;
const collX = new Set(JSON.parse(fs.readFileSync("/tmp/coll-x.json", "utf8")).products.map(p => p.handle));
const strip = h => h.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
const esc = s => s.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/"/g, '\\"');

let out = `/* AUTO-GENERATED by scripts/gen-xcom-seed.cjs — mirror of shop.x.com catalog */
import type { ProductSeedX } from "./seed-types";

export const xcomCategories = [
  {
    name: "X Collection",
    nameEn: "X Collection",
    slug: "x-collection",
    description: "Official X collection",
    image: "/images/xcom2/banner-x.jpg",
    sortOrder: 1,
  },
  {
    name: "SpaceXAI Collection",
    nameEn: "SpaceXAI Collection",
    slug: "spacexai-collection",
    description: "Official SpaceXAI collection",
    image: "/images/xcom2/banner-xai.jpg",
    sortOrder: 2,
  },
];

export const xcomProducts: ProductSeedX[] = [
`;

for (const p of products) {
  const imgs = p.images.map((im, i) => `/images/xcom2/${p.handle}-${i}.jpg`);
  const price = Number(p.variants[0]?.price ?? 0);
  const anyAvail = p.variants.some(v => v.available);
  const presale = p.handle.includes("pre-sale") || p.tags.includes("pre-order") || p.tags.includes("presale");
  const attrs = p.options
    .filter(o => o.name !== "Title")
    .map((o, oi) => {
      // 每个规格值的可用性来自变体级 available 字段
      const soldOutValues = o.values.filter(
        v => !p.variants.some(vv => vv[`option${oi + 1}`] === v && vv.available),
      );
      return { name: o.name, values: o.values, selectable: true, ...(soldOutValues.length ? { soldOutValues } : {}) };
    });
  const desc = strip(p.body_html || p.title);
  const cat = collX.has(p.handle) ? "x-collection" : "spacexai-collection";
  out += `  {
    name: ${JSON.stringify(p.title)},
    nameEn: ${JSON.stringify(p.title)},
    slug: ${JSON.stringify(p.handle)},
    sku: ${JSON.stringify("xcm-" + p.handle)},
    categorySlug: ${JSON.stringify(cat)},
    price: ${price.toFixed(2)},
    stock: ${anyAvail ? 50 : 0},
    soldCount: 0,
    isPresale: ${presale},
    images: ${JSON.stringify(imgs)},
    attributes: ${JSON.stringify(attrs)},
    description: ${JSON.stringify(desc)},
  },
`;
}
out += "];\n";
fs.writeFileSync("prisma/xcom-catalog.ts", out);
console.log("written prisma/xcom-catalog.ts,", products.length, "products");
