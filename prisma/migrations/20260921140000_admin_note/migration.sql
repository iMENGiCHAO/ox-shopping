-- 管理端订单「内部备注」字段：`orders.adminNote TEXT NULL`。
--
-- 背景（商业交付缺陷 P1-8）：运营需要在订单上留内部处理说明
-- （例如「已电话确认改址」「客户要求延迟发货」「已补发优惠券」），
-- 但 Order 只有 `note` —— 那是**顾客**下单时填的备注，运营改写会丢失顾客原话，
-- 也没有任何"仅内部可见"的字段可落库（此前只能写进审计日志，检索困难）。
-- 与 note 分离后：顾客备注保持原样，内部备注只出现在管理端。

ALTER TABLE "orders" ADD COLUMN "adminNote" TEXT;
